export function trackLearningDay(date: string): void {
  const days = loadLearningDays();
  if (!days.includes(date)) {
    days.push(date);
    days.sort();
    localStorage.setItem(STORAGE_KEYS.learningDays(), JSON.stringify(days));
  }
}

