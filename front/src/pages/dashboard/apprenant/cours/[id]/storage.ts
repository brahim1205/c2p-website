export function formatLearningTime(totalSeconds: number): string {
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  if (hours > 0) return `${hours}h ${minutes}min`;
  return `${minutes}min`;
}

export function getCourseLearningTime(courseId: number): number {
  return loadSessionTime(courseId);
}

export function getAllCoursesLearningTime(): Record<number, number> {
  const result: Record<number, number> = {};
  const history = loadCourseHistory();
  for (const entry of history) {
    const seconds = loadSessionTime(entry.courseId);
    if (seconds > 0) result[entry.courseId] = seconds;
  }
  return result;
}
