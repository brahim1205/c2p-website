export function updateLeaderboardUser(entry: LeaderboardEntry): void {
  const board = loadLeaderboard();
  const idx = board.findIndex((e) => e.id === entry.id);
  if (idx >= 0) {
    board[idx] = { ...board[idx], ...entry, isCurrentUser: true };
  } else {
    board.push({ ...entry, isCurrentUser: true });
  }
  board.sort((a, b) => b.xp - a.xp);
  saveLeaderboard(board);
}

export function getRank(): number {
  const board = loadLeaderboard();
  const me = board.find((e) => e.isCurrentUser);
  if (!me) return board.length + 1;
  return board.findIndex((e) => e.id === me.id) + 1;
}

