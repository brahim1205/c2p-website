export function addXP(amount: number): number {
  const current = loadXP();
  const next = current + amount;
  saveXP(next);
  // Track daily XP
  const today = new Date().toISOString().split('T')[0];
  const daily = loadDailyXP(today);
  saveDailyXP(today, daily + amount);
  // Track learning day
  trackLearningDay(today);
  return next;
}

