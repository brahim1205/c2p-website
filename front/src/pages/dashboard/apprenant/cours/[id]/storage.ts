export function getCurrentStreak(): number {
  const days = loadLearningDays();
  if (days.length === 0) return 0;
  const sorted = [...days].sort();
  let streak = 0;
  const today = new Date().toISOString().split('T')[0];
  const yesterday = new Date(Date.now() - 86400000).toISOString().split('T')[0];
  if (!sorted.includes(today) && !sorted.includes(yesterday)) return 0;

  for (let i = sorted.length - 1; i >= 0; i--) {
    const d = sorted[i];
    if (d === today || d === yesterday) {
      streak = 1;
      let check = new Date(d + 'T00:00:00');
      for (let j = i - 1; j >= 0; j--) {
        const prev = new Date(sorted[j] + 'T00:00:00');
        const diff = Math.round((check.getTime() - prev.getTime()) / 86400000);
        if (diff === 1) {
          streak++;
          check = prev;
        } else {
          break;
        }
      }
      break;
    }
  }
  return streak;
}

export function getLearningDaysForHeatmap(daysBack = 84): Record<string, number> {
  const days = loadLearningDays();
  const dailyXP: Record<string, number> = {};
  const today = new Date();
  for (let i = 0; i < daysBack; i++) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const ds = d.toISOString().split('T')[0];
    if (days.includes(ds)) {
      dailyXP[ds] = loadDailyXP(ds);
    }
  }
  return dailyXP;
}

