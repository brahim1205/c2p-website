export function checkAndAwardBadges(
  courseId: number,
  completedLessons: Set<number>,
  bookmarkedLessons: Set<number>,
  notes: Record<number, string>,
  quizScore?: { score: number; total: number },
  totalCourseLessons?: number,
): string[] {
  const newlyUnlocked: string[] = [];
  const totalLessonsCount = completedLessons.size;
  const totalBookmarks = bookmarkedLessons.size;
  const totalNotes = Object.values(notes).filter((n) => n.trim()).length;

  if (totalLessonsCount >= 1 && unlockBadge('starter')) newlyUnlocked.push('starter');

  if (totalCourseLessons && totalLessonsCount >= Math.ceil(totalCourseLessons * 0.5)) {
    if (unlockBadge('halfway')) newlyUnlocked.push('halfway');
  }

  if (totalCourseLessons && totalLessonsCount >= totalCourseLessons) {
    if (unlockBadge('finisher')) newlyUnlocked.push('finisher');
  }

  if (quizScore && quizScore.score === quizScore.total && quizScore.total >= 3) {
    if (unlockBadge('quiz-master')) newlyUnlocked.push('quiz-master');
  }
  if (totalNotes >= 5) {
    if (unlockBadge('note-taker')) newlyUnlocked.push('note-taker');
  }
  if (totalBookmarks >= 10) {
    if (unlockBadge('bookmarker')) newlyUnlocked.push('bookmarker');
  }

  // XP-based badges
  const xp = loadXP();
  if (xp >= 1000 && unlockBadge('xp-1000')) newlyUnlocked.push('xp-1000');
  if (xp >= 5000 && unlockBadge('xp-5000')) newlyUnlocked.push('xp-5000');

  // Streak badges
  const streak = getCurrentStreak();
  if (streak >= 7 && unlockBadge('streak-7')) newlyUnlocked.push('streak-7');
  if (streak >= 30 && unlockBadge('streak-30')) newlyUnlocked.push('streak-30');

  // Course diversity
  const history = loadCourseHistory();
  if (history.length >= 5 && unlockBadge('courses-5')) newlyUnlocked.push('courses-5');
  const completedCourses = history.filter((h) => h.progress === 100).length;
  if (completedCourses >= 3 && unlockBadge('courses-3-done')) newlyUnlocked.push('courses-3-done');

  return newlyUnlocked;
}

